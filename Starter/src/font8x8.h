static inline const uint8_t *starter_get_glyph(uint32_t cp) {
    if (cp >= 0x20 && cp <= 0x7E) {
        return g_font8x8_ascii[cp - 0x20];
    }
    switch (cp) {
    case 0xC4: return g_glyph_A_uml;
    case 0xD6: return g_glyph_O_uml;
    case 0xDC: return g_glyph_U_uml;
    case 0xE4: return g_glyph_a_uml;
    case 0xF6: return g_glyph_o_uml;
    case 0xFC: return g_glyph_u_uml;
    case 0xDF: return g_glyph_sz;
    case 0x2013: case 0x2014: return g_font8x8_ascii['-' - 0x20];
    default:   return g_font8x8_ascii['?' - 0x20];
    }
}

/* Liest ein UTF-8- oder Latin-1-Zeichen und rückt den Zeiger weiter */
static inline uint32_t starter_next_codepoint(const char **p) {
    const unsigned char *s = (const unsigned char *)(*p);
    if (!s || !s[0]) return 0;
    if (s[0] < 0x80) {
        *p += 1;
        return s[0];
    }
    if ((s[0] & 0xE0) == 0xC0 && (s[1] & 0xC0) == 0x80) {
        uint32_t cp = ((uint32_t)(s[0] & 0x1F) << 6) | (uint32_t)(s[1] & 0x3F);
        *p += 2;
        return cp;
    }
    if ((s[0] & 0xF0) == 0xE0 && (s[1] & 0xC0) == 0x80 && (s[2] & 0xC0) == 0x80) {
        uint32_t cp = ((uint32_t)(s[0] & 0x0F) << 12) | ((uint32_t)(s[1] & 0x3F) << 6) | (uint32_t)(s[2] & 0x3F);
        *p += 3;
        return cp;
    }
    *p += 1;
    return s[0];
}

